#!/bin/bash
set -euo pipefail
cd /home/saniya/flight-delay-analytics

echo "============================================================"
echo "A1: INDEPENDENT DISTRIBUTION CHECK ON FLIGHTS_ENRICHED"
echo "============================================================"

.venv/bin/python - << 'EOF'
from src.utils.spark_session import get_spark_session
import pyspark.sql.functions as F

spark = get_spark_session("a1_distribution_check")
df = spark.read.parquet("hdfs://localhost:9000/user/saniya/flight_delay/processed/flights_enriched")

print("--- 1. DISTANCE_BAND Distribution ---")
df.groupBy("DISTANCE_BAND").count().withColumn("pct", F.round(F.col("count") / 5819079 * 100, 2)).orderBy(F.desc("count")).show()

print("--- 2. DELAY_CATEGORY Distribution ---")
df.groupBy("DELAY_CATEGORY").count().withColumn("pct", F.round(F.col("count") / 5819079 * 100, 2)).orderBy(F.desc("count")).show()

print("--- 3. PRIMARY_DELAY_CAUSE Distribution ---")
df.groupBy("PRIMARY_DELAY_CAUSE").count().withColumn("pct", F.round(F.col("count") / 5819079 * 100, 2)).orderBy(F.desc("count")).show()

print("--- 4. NULL ORIGIN_LAT & DEST_LAT Counts and Breakdown ---")
null_orig_lat = df.filter(F.col("ORIGIN_LAT").isNull()).count()
null_dest_lat = df.filter(F.col("DEST_LAT").isNull()).count()
orig_unmapped = df.filter(F.col("ORIGIN_UNMAPPED") == 1).count()
dest_unmapped = df.filter(F.col("DEST_UNMAPPED") == 1).count()
print(f"Total Null ORIGIN_LAT: {null_orig_lat:,} (ORIGIN_UNMAPPED = {orig_unmapped:,})")
print(f"Total Null DEST_LAT:   {null_dest_lat:,} (DEST_UNMAPPED = {dest_unmapped:,})")

print("\nBreakdown of Null ORIGIN_LAT by Origin Airport:")
df.filter(F.col("ORIGIN_LAT").isNull()).groupBy("ORIGIN_AIRPORT", "ORIGIN_UNMAPPED").count().orderBy(F.desc("count")).show()

print("\nBreakdown of Null DEST_LAT by Destination Airport:")
df.filter(F.col("DEST_LAT").isNull()).groupBy("DESTINATION_AIRPORT", "DEST_UNMAPPED").count().orderBy(F.desc("count")).show()

spark.stop()
EOF

