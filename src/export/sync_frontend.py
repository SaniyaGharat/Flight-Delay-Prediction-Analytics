#!/usr/bin/env python3
"""
src/export/sync_frontend.py

Connects and synchronizes backend analytical outputs to the frontend application:
1. Validates source tables generated by the Big Data pipeline (output/powerbi or HDFS)
2. Derives airport summary aggregations (airport_origin_totals.csv, airport_dest_totals.csv)
3. Formats machine learning summary (ml_summary.json)
4. Copies all required dataset files directly to frontend/public/data/
5. Runs verification checks to guarantee the frontend dashboard loads with 0 errors
"""

import os
import sys
import json
import shutil
from pathlib import Path

# Paths
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
FRONTEND_DATA_DIR = PROJECT_ROOT / "frontend" / "public" / "data"
LOCAL_POWERBI_DIR = PROJECT_ROOT / "output" / "powerbi"
WSL_POWERBI_DIR = Path("/home/saniya/flight-delay-analytics/output/powerbi")

REQUIRED_FRONTEND_FILES = [
    "dim_date.csv",
    "dim_airline.csv",
    "dim_airport.csv",
    "fact_daily_airline.csv",
    "fact_airline_dow_hour.csv",
    "fact_route_month.csv",
    "fact_cause_daily_airline.csv",
    "fact_cancel_daily_airline_reason.csv",
    "airport_origin_totals.csv",
    "airport_dest_totals.csv",
    "ml_summary.json"
]

def find_source_dir() -> Path:
    """Finds the most complete source directory containing exported backend tables."""
    # Check project local output/powerbi first
    if LOCAL_POWERBI_DIR.exists():
        present = [f for f in REQUIRED_FRONTEND_FILES if (LOCAL_POWERBI_DIR / f).is_file()]
        if len(present) >= len(REQUIRED_FRONTEND_FILES) - 2:
            return LOCAL_POWERBI_DIR
            
    # Check WSL path if running inside Linux/WSL
    if WSL_POWERBI_DIR.exists():
        present = [f for f in REQUIRED_FRONTEND_FILES if (WSL_POWERBI_DIR / f).is_file()]
        if len(present) >= len(REQUIRED_FRONTEND_FILES) - 2:
            return WSL_POWERBI_DIR

    return LOCAL_POWERBI_DIR

def generate_airport_totals(source_dir: Path):
    """Generates airport_origin_totals.csv and airport_dest_totals.csv if missing."""
    origin_totals_path = source_dir / "airport_origin_totals.csv"
    dest_totals_path = source_dir / "airport_dest_totals.csv"
    
    if origin_totals_path.exists() and dest_totals_path.exists():
        return

    try:
        import pandas as pd
        daily_origin = source_dir / "fact_daily_origin.csv"
        daily_dest = source_dir / "fact_daily_dest.csv"
        dim_airport = source_dir / "dim_airport.csv"

        if daily_origin.exists() and daily_dest.exists() and dim_airport.exists():
            print("[INFO] Generating airport summary aggregates...")
            agg_cols = [
                "total_flights", "flown_flights", "cancelled_flights",
                "diverted_flights", "delayed_arr_15", "sum_arr_delay_min"
            ]
            
            def aggregate_totals(csv_path, group_key):
                df = pd.read_csv(csv_path).fillna(0)
                return df.groupby(group_key)[agg_cols].sum().reset_index().rename(columns={group_key: "code"})

            df_origin = aggregate_totals(daily_origin, "ORIGIN_AIRPORT")
            df_dest = aggregate_totals(daily_dest, "DEST_AIRPORT")
            df_airport = pd.read_csv(dim_airport)

            df_origin.merge(df_airport, on="code", how="left").to_csv(origin_totals_path, index=False)
            df_dest.merge(df_airport, on="code", how="left").to_csv(dest_totals_path, index=False)
            print("[SUCCESS] Airport totals generated successfully.")
    except Exception as e:
        print(f"[WARNING] Could not auto-generate airport totals: {e}")

def sync_data(source_dir: Path, target_dir: Path) -> dict:
    """Copies all required data files from backend export to frontend directory."""
    target_dir.mkdir(parents=True, exist_ok=True)
    results = {}
    
    for filename in REQUIRED_FRONTEND_FILES:
        src = source_dir / filename
        dst = target_dir / filename
        
        if src.is_file():
            shutil.copy2(src, dst)
            size_kb = dst.stat().st_size / 1024
            results[filename] = {"status": "synced", "size_kb": round(size_kb, 2)}
        elif dst.is_file():
            size_kb = dst.stat().st_size / 1024
            results[filename] = {"status": "already_present", "size_kb": round(size_kb, 2)}
        else:
            results[filename] = {"status": "missing", "size_kb": 0}
            
    return results

def verify_frontend_data(target_dir: Path) -> bool:
    """Asserts that all required files exist in frontend and have valid sizes."""
    print("\n" + "=" * 70)
    print("VERIFYING FRONTEND DATA CONNECTION")
    print("=" * 70)
    all_ok = True
    
    for filename in REQUIRED_FRONTEND_FILES:
        filepath = target_dir / filename
        if not filepath.is_file():
            print(f"  [FAIL] Missing file: {filename}")
            all_ok = False
            continue
            
        size = filepath.stat().st_size
        if size == 0:
            print(f"  [FAIL] File is empty (0 bytes): {filename}")
            all_ok = False
            continue
            
        print(f"  [OK]   {filename:<35} ({size:>10,} bytes)")
        
    print("=" * 70)
    if all_ok:
        print("[SUCCESS] All frontend backend connections verified! Dashboard is ready.")
    else:
        print("[ERROR] Some data connections are missing or incomplete.")
    print("=" * 70 + "\n")
    return all_ok

def main():
    source_dir = find_source_dir()
    print(f"[INFO] Source backend directory: {source_dir}")
    print(f"[INFO] Target frontend directory: {FRONTEND_DATA_DIR}")
    
    generate_airport_totals(source_dir)
    sync_results = sync_data(source_dir, FRONTEND_DATA_DIR)
    
    # Also ensure local powerbi output has latest
    if source_dir != LOCAL_POWERBI_DIR and LOCAL_POWERBI_DIR.exists():
        sync_data(source_dir, LOCAL_POWERBI_DIR)
        
    success = verify_frontend_data(FRONTEND_DATA_DIR)
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()
